def _knowledge_dbs(tmp_path):
    yield "sqlite", _sqlite_db(tmp_path, "km")
    if os.getenv("TEST_POSTGRES_URL"):
        pg = _pg_db()
        _truncate_pg(pg)
        yield "postgres", pg


def _doc_payload(tmp_path, i: int) -> dict:
    return {
        "title": f"t-{i}",
        "source_uri": _safe_uri(tmp_path, f"f-{i}"),
        "mime_type": "text/plain",
        "metadata": {"author": "ops", "i": i},
        "acl_tags": ["ops-team"],
        "version": "v1",
    }


def test_transition_status_round_trip(tmp_path) -> None:
    for _label, db in _knowledge_dbs(tmp_path):
        store = _knowledge_store(db, tmp_path)
        doc_id = store.create_document(**_doc_payload(tmp_path, 0))
        out = store.transition_status(doc_id, "parsing")
        assert out["parse_status"] == "parsing"
        out = store.transition_status(doc_id, "ready")
        assert out["parse_status"] == "ready"
        out = store.transition_status(doc_id, "published")
        assert out["parse_status"] == "published"


def test_mark_parse_failed_sets_error(tmp_path) -> None:
    for _label, db in _knowledge_dbs(tmp_path):
        store = _knowledge_store(db, tmp_path)
        doc_id = store.create_document(**_doc_payload(tmp_path, 1))
        store.mark_parse_failed(doc_id, "boom", stage="ocr")
        doc = store.get_document(doc_id)
        assert doc["parse_status"] == "parse_failed"
        assert "[ocr] boom" in doc["parse_error"]


def test_write_chunks_marks_ready(tmp_path) -> None:
    for _label, db in _knowledge_dbs(tmp_path):
        store = _knowledge_store(db, tmp_path)
        doc_id = store.create_document(**_doc_payload(tmp_path, 2))
        chunks = [
            {
                "chunk_id": f"{doc_id}_chunk_{i:03d}",
                "chunk_no": i,
                "content": f"content {i}",
                "section_path": "root",
                "table_id": None,
                "row_id": None,
            }
            for i in range(3)
        ]
        embeddings = [[0.1, 0.2, 0.3] for _ in chunks]
        store.write_chunks(
            doc_id=doc_id,
            chunks=chunks,
            embeddings=embeddings,
            embedding_model="bge-m3",
            acl_tags_override=["ops-team"],
        )
        doc = store.get_document(doc_id)
        assert doc["parse_status"] == "ready"
        assert doc["chunk_count"] == 3
        stored = store.get_chunks_for_doc(doc_id)
        assert [c["chunk_no"] for c in stored] == [0, 1, 2]


def test_write_qa_log_and_list(tmp_path) -> None:
    for _label, db in _knowledge_dbs(tmp_path):
        store = _knowledge_store(db, tmp_path)
        store.write_qa_log(
            qa_log_id="qa_001",
            session_id="s1",
            user_id="alice",
            question="q",
            rewritten_query=None,
            knowledge_scopes=["ops-team"],
            retrieved_chunks=[{"chunk_id": "c1", "score": 0.9}],
            answer="a",
            model_name="bge-m3",
            prompt_version="v1",
            confidence=0.7,
            latency_ms=120,
            trace_id="trace-1",
        )
        items, total = store.list_qa_logs(session_id="s1", page=1, page_size=10)
        assert total == 1
        assert items[0]["qa_log_id"] == "qa_001"
        assert items[0]["knowledge_scopes"] == ["ops-team"]
        full = store.get_qa_log("trace-1")
        assert full is not None
        assert full["qa_log_id"] == "qa_001"
        assert full["retrieved_chunks"] == [{"chunk_id": "c1", "score": 0.9}]


def test_write_feedback_and_list(tmp_path) -> None:
    for _label, db in _knowledge_dbs(tmp_path):
        store = _knowledge_store(db, tmp_path)
        fid = store.write_feedback(
            trace_id="trace-1", feedback_type="up", comment="good",
        )
        assert fid.startswith("fb_")
        items, total = store.list_feedbacks(trace_id="trace-1")
        assert total == 1
        assert items[0]["feedback_id"] == fid
        assert items[0]["feedback_type"] == "up"


def test_list_documents_paginated(tmp_path) -> None:
    for _label, db in _knowledge_dbs(tmp_path):
        store = _knowledge_store(db, tmp_path)
        for i in range(5):
            store.create_document(**_doc_payload(tmp_path, i))
        items, total = store.list_documents(page=1, page_size=2)
        assert total == 5
        assert len(items) == 2
        items, total = store.list_documents(page=3, page_size=2)
        assert total == 5
        assert len(items) == 1


def test_list_documents_filter_by_status(tmp_path) -> None:
    for _label, db in _knowledge_dbs(tmp_path):
        store = _knowledge_store(db, tmp_path)
        for i in range(3):
            doc_id = store.create_document(**_doc_payload(tmp_path, i))
            if i == 0:
                store.transition_status(doc_id, "parsing")
                store.transition_status(doc_id, "ready")
                store.transition_status(doc_id, "published")
        published, total = store.list_documents(status="published")
        assert total == 1
        assert published[0]["parse_status"] == "published"
